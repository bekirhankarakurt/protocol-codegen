void emit_enum(std::ostream& o, const EnumDef& e) {
    const std::string type = prim_cpp_name(e.underlying);
    o << "enum class " << e.name << " : " << type << " {\n";
    for (const EnumValue& v : e.values) o << "    " << v.name << " = " << v.value << ",\n";
    o << "};\n\n";
    o << "[[nodiscard]] constexpr bool is_valid(" << e.name << " value) noexcept {\n"
      << "    switch (value) {\n";
    for (const EnumValue& v : e.values) o << "        case " << e.name << "::" << v.name << ":\n";
    o << "            return true;\n    }\n    return false;\n}\n\n";
    o << "[[nodiscard]] constexpr const char* to_string(" << e.name << " value) noexcept {\n"
      << "    switch (value) {\n";
    for (const EnumValue& v : e.values) {
        o << "        case " << e.name << "::" << v.name << ": return \"" << v.name << "\";\n";
    }
    o << "    }\n    return \"Unknown\";\n}\n\n";
}

std::string member_type(const Schema& s, const Field& f) {
    if (f.kind == FieldKind::Text) return "std::array<char, " + std::to_string(f.count) + ">";
    const std::string base = f.kind == FieldKind::Enum ? s.enums[f.enum_index].name : prim_cpp_name(f.prim);
    return f.is_array ? "std::array<" + base + ", " + std::to_string(f.count) + ">" : base;
}

std::string put_stmt(const Schema& s, const Field& f, const std::string& tag, const std::string& value) {
    std::string arg = value;
    if (f.kind == FieldKind::Enum) {
        arg = std::string("static_cast<") + prim_cpp_name(field_prim(s, f)) + ">(" + value + ")";
    } else if (f.kind == FieldKind::Prim && f.prim == Prim::Bool) {
        arg = "static_cast<std::uint8_t>(" + value + ")";
    }
    return "writer_.put<" + tag + ">(" + arg + ");";
}

std::string get_stmt(const Field& f, const std::string& tag, const std::string& target) {
    if (f.kind == FieldKind::Enum) return "reader_.get_enum<" + tag + ">(" + target + ");";
    if (f.kind == FieldKind::Prim && f.prim == Prim::Bool) return "reader_.get_bool(" + target + ");";
    return "reader_.get<" + tag + ">(" + target + ");";
}

void emit_message(std::ostream& o, const Schema& s, const Message& m) {
    const std::string tag = endian_tag(m.endian);
    if (!m.doc.empty()) o << "/// " << m.doc << '\n';
    o << "struct " << m.name << " {\n"
      << "    static constexpr std::uint16_t kId = " << m.id << ";\n"
      << "    static constexpr std::uint8_t kSince = " << static_cast<unsigned>(m.since) << ";\n"
      << "    static constexpr std::size_t kWireSize = " << m.wire_size << ";\n"
      << "    static constexpr const char* kName = \"" << m.name << "\";\n\n";
    for (const Field& f : m.fields) {
        o << "    " << member_type(s, f) << ' ' << f.name << "{};";
        if (!f.doc.empty()) o << "  ///< " << f.doc;
        o << '\n';
    }
    o << "\n    [[nodiscard]] Status encode(Writer& writer_) const noexcept {\n";
    for (const Field& f : m.fields) {
        if (f.kind == FieldKind::Text) {
            o << "        writer_.put_text(" << f.name << ".data(), " << f.name << ".size());\n";
        } else if (f.is_array) {
            o << "        for (const auto& element_ : " << f.name << ") { "
              << put_stmt(s, f, tag, "element_") << " }\n";
        } else {
            o << "        " << put_stmt(s, f, tag, f.name) << '\n';
        }
    }
    o << "        return writer_.status();\n    }\n\n"
      << "    [[nodiscard]] Status decode(Reader& reader_) noexcept {\n";
    for (const Field& f : m.fields) {
        if (f.kind == FieldKind::Text) {
            o << "        reader_.get_text(" << f.name << ".data(), " << f.name << ".size());\n";
        } else if (f.is_array) {
            o << "        for (auto& element_ : " << f.name << ") { " << get_stmt(f, tag, "element_")
              << " }\n";
        } else {
            o << "        " << get_stmt(f, tag, f.name) << '\n';
        }
    }
    o << "        return reader_.status();\n    }\n\n"
      << "    [[nodiscard]] friend bool operator==(const " << m.name << "& lhs_, const " << m.name
      << "& rhs_) noexcept {\n        return ";
    for (std::size_t i = 0; i < m.fields.size(); ++i) {
        if (i != 0) o << "\n               && ";
        o << "lhs_." << m.fields[i].name << " == rhs_." << m.fields[i].name;
    }
    o << ";\n    }\n    [[nodiscard]] friend bool operator!=(const " << m.name << "& lhs_, const "
      << m.name << "& rhs_) noexcept {\n        return !(lhs_ == rhs_);\n    }\n};\n\n";
}

std::string crc_function(CrcKind crc) {
    if (crc == CrcKind::Crc16) {
        return R"(// CRC-16/CCITT-FALSE: poly 0x1021, init 0xFFFF, no reflection, no final XOR.
[[nodiscard]] inline std::uint16_t crc16_ccitt_false(const std::uint8_t* data, std::size_t size) noexcept {
    std::uint32_t crc = 0xFFFFU;
    for (std::size_t i = 0; i < size; ++i) {
        crc ^= static_cast<std::uint32_t>(data[i]) << 8U;
        for (int bit = 0; bit < 8; ++bit) {
            crc = ((crc & 0x8000U) != 0U ? (crc << 1U) ^ 0x1021U : crc << 1U) & 0xFFFFU;
        }
    }
    return static_cast<std::uint16_t>(crc);
}

[[nodiscard]] inline Crc frame_crc(const std::uint8_t* data, std::size_t size) noexcept {
    return crc16_ccitt_false(data, size);
})";
    }
    return R"(// CRC-32/ISO-HDLC (IEEE 802.3): reflected poly 0xEDB88320, init and final XOR 0xFFFFFFFF.
[[nodiscard]] inline std::uint32_t crc32_ieee(const std::uint8_t* data, std::size_t size) noexcept {
    std::uint32_t crc = 0xFFFFFFFFU;
    for (std::size_t i = 0; i < size; ++i) {
        crc ^= static_cast<std::uint32_t>(data[i]);
        for (int bit = 0; bit < 8; ++bit) {
            crc = (crc & 1U) != 0U ? (crc >> 1U) ^ 0xEDB88320U : crc >> 1U;
        }
    }
    return crc ^ 0xFFFFFFFFU;
}

[[nodiscard]] inline Crc frame_crc(const std::uint8_t* data, std::size_t size) noexcept {
    return crc32_ieee(data, size);
})";
}

