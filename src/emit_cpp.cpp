// Bounds-checked sequential writer. Writes past the end set a sticky error.
class Writer {
public:
    Writer(std::uint8_t* data, std::size_t capacity) noexcept : data_(data), capacity_(capacity) {}

    template <Endian E, typename T>
    void put(T value) noexcept {
        static_assert(std::is_arithmetic_v<T>, "arithmetic types only");
        using U = typename detail::UnsignedOf<sizeof(T)>::type;
        if (!reserve(sizeof(T))) return;
        U bits{};
        if constexpr (std::is_floating_point_v<T>) {
            std::memcpy(&bits, &value, sizeof(T));
        } else {
            bits = static_cast<U>(value);
        }
        for (std::size_t i = 0; i < sizeof(T); ++i) {
            const std::size_t shift = 8U * (E == Endian::Little ? i : sizeof(T) - 1U - i);
            data_[pos_ + i] = static_cast<std::uint8_t>((bits >> shift) & 0xFFU);
        }
        pos_ += sizeof(T);
    }

    void put_text(const char* text, std::size_t size) noexcept {
        if (!reserve(size)) return;
        std::memcpy(data_ + pos_, text, size);
        pos_ += size;
    }

    [[nodiscard]] Status status() const noexcept {
        return overflow_ ? Status::BufferTooSmall : Status::Ok;
    }
    [[nodiscard]] std::size_t size() const noexcept { return pos_; }

private:
    bool reserve(std::size_t count) noexcept {
        if (overflow_ || capacity_ - pos_ < count) {
            overflow_ = true;
            return false;
        }
        return true;
    }

    std::uint8_t* data_;
    std::size_t capacity_;
    std::size_t pos_ = 0;
    bool overflow_ = false;
};

// Bounds-checked sequential reader. The first failure is sticky; later reads are no-ops.
class Reader {
public:
    Reader(const std::uint8_t* data, std::size_t size) noexcept : data_(data), size_(size) {}

    template <Endian E, typename T>
    void get(T& out) noexcept {
        static_assert(std::is_arithmetic_v<T>, "arithmetic types only");
        using U = typename detail::UnsignedOf<sizeof(T)>::type;
        if (!take(sizeof(T))) return;
        U bits{};
        for (std::size_t i = 0; i < sizeof(T); ++i) {
            const std::size_t shift = 8U * (E == Endian::Little ? i : sizeof(T) - 1U - i);
            bits = static_cast<U>(bits | (static_cast<U>(data_[pos_ + i]) << shift));
        }
        pos_ += sizeof(T);
        if constexpr (std::is_floating_point_v<T>) {
            std::memcpy(&out, &bits, sizeof(T));
        } else {
            out = static_cast<T>(bits);
        }
    }

    void get_bool(bool& out) noexcept {
        std::uint8_t raw{};
        get<Endian::Little>(raw);
        if (status_ != Status::Ok) return;
        if (raw > 1U) {
            status_ = Status::InvalidValue;
            return;
        }
        out = raw != 0U;
    }

    template <Endian E, typename En>
    void get_enum(En& out) noexcept {
        std::underlying_type_t<En> raw{};
        get<E>(raw);
        if (status_ != Status::Ok) return;
        const En candidate = static_cast<En>(raw);
        if (!is_valid(candidate)) {
            status_ = Status::InvalidValue;
            return;
        }
        out = candidate;
    }

    void get_text(char* dest, std::size_t size) noexcept {
        if (!take(size)) return;
        std::memcpy(dest, data_ + pos_, size);
        pos_ += size;
    }

    [[nodiscard]] Status status() const noexcept { return status_; }

private:
    bool take(std::size_t count) noexcept {
        if (status_ != Status::Ok) return false;
        if (size_ - pos_ < count) {
            status_ = Status::Truncated;
            return false;
        }
        return true;
    }

    const std::uint8_t* data_;
    std::size_t size_;
    std::size_t pos_ = 0;
    Status status_ = Status::Ok;
};

