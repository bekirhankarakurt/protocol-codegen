std::string emit_cpp(const Schema& s, std::string_view source_name) {
    std::ostringstream o;
    o << substitute(kPreamble, {{"@SRC@", std::string(source_name)},
                                {"@NS@", s.name},
                                {"@SYNC@", hex_byte(s.sync)},
                                {"@VERSION@", std::to_string(s.version)},
                                {"@CRC_SIZE@", std::to_string(crc_size(s.crc))},
                                {"@FRAME_ENDIAN@", endian_tag(s.endian)},
                                {"@CRC_TYPE@", s.crc == CrcKind::Crc16 ? "std::uint16_t" : "std::uint32_t"}});
    for (const EnumDef& e : s.enums) emit_enum(o, e);
    o << substitute(kRuntime, {{"@CRC_FN@", crc_function(s.crc)}});
    for (const Message& m : s.messages) emit_message(o, s, m);

    o << "using Message = std::variant<";
    for (std::size_t i = 0; i < s.messages.size(); ++i) o << (i == 0 ? "" : ", ") << s.messages[i].name;
    o << ">;\n";

    std::string dispatch;
    for (const Message& m : s.messages) {
        dispatch += "        case " + m.name + "::kId:\n            status = detail::decode_payload<" + m.name +
                    ">(payload, length, version, out);\n            break;\n";
    }
    o << substitute(kFraming, {{"@DISPATCH@", dispatch}, {"@NS@", s.name}});
    return o.str();
}

